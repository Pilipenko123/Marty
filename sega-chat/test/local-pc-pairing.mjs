// Испытательная схема: ещё нет работающего UI, установщика и проверки восстановления после отключения питания.
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
const p=createRequire(import.meta.url)('../local-pc/pairing.js');
const subtle=crypto.webcrypto.subtle, algo={name:'ECDH',namedCurve:'P-256'};
const keys=await subtle.generateKey(algo,true,['deriveBits']);
const exported=await subtle.exportKey('pkcs8',keys.privateKey);
const anotherDevice=await subtle.importKey('pkcs8',exported,algo,false,['deriveBits']);
const anotherPerson=await subtle.generateKey(algo,true,['deriveBits']);
const userId='a'.repeat(18), url='https://chat.example/';
const generated=await p.create({url,userId,privateKey:keys.privateKey,publicKey:keys.publicKey});
const agent=p.parse(generated.code,'https://chat.example');
assert.equal(agent.url,'https://chat.example');
assert.equal(agent.deviceId,generated.registration.id);
assert.equal(agent.secret.length,32);
assert.equal(generated.registration.tokenHash,crypto.createHash('sha256').update(agent.token).digest('hex'));
assert(!JSON.stringify(generated.registration).includes(agent.token));
assert(!JSON.stringify(generated.registration).includes(Buffer.from(agent.secret).toString('base64url')));
const recovered=await p.recover({userId,deviceId:agent.deviceId,wrappedKey:generated.registration.wrappedKey,privateKey:anotherDevice,publicKey:keys.publicKey});
assert(Buffer.from(recovered).equals(Buffer.from(agent.secret)));
await assert.rejects(p.recover({userId,deviceId:agent.deviceId,wrappedKey:generated.registration.wrappedKey,privateKey:anotherPerson.privateKey,publicKey:keys.publicKey}));
await assert.rejects(p.recover({userId:'b'.repeat(18),deviceId:agent.deviceId,wrappedKey:generated.registration.wrappedKey,privateKey:keys.privateKey,publicKey:keys.publicKey}));
await assert.rejects(p.recover({userId,deviceId:'c'.repeat(32),wrappedKey:generated.registration.wrappedKey,privateKey:keys.privateKey,publicKey:keys.publicKey}));
const wrap=generated.registration.wrappedKey, tampered=(wrap[0]==='A'?'B':'A')+wrap.slice(1);
await assert.rejects(p.recover({userId,deviceId:agent.deviceId,wrappedKey:tampered,privateKey:keys.privateKey,publicKey:keys.publicKey}));
assert.throws(()=>p.parse(generated.code,'https://other.example'));
assert.throws(()=>p.parse(generated.code,'https://chat.example:444'));
assert.throws(()=>p.parse(generated.code,'https://chat.example/other'));
assert.equal(p.parse(generated.code,'https://CHAT.EXAMPLE:443/').url,'https://chat.example');
assert.throws(()=>p.normalizeUrl({toString:()=>url}));
assert.throws(()=>p.normalizeUrl('https://chat.example/'+'a'.repeat(2048)));
assert.throws(()=>p.parse('not-a-code'));
for (const bad of ['http://chat.example','https://user:password@chat.example','https://chat.example/?token=secret','https://chat.example/#x']) await assert.rejects(p.create({url:bad,userId,privateKey:keys.privateKey,publicKey:keys.publicKey}));
const separate=await p.create({url,userId,privateKey:keys.privateKey,publicKey:keys.publicKey});
assert.notEqual(separate.registration.id,generated.registration.id);
assert.notEqual(separate.code,generated.code);
console.log('local-pc-pairing: создание кода и восстановление ключа проверены; проверка реального установщика и Windows ещё нужна');
