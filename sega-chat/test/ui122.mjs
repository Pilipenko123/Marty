// test/ui122.mjs — pkg3-122: у друзей владельца подключение Яндекс.Диска
// упиралось в чужую страницу «400 · Неизвестно приложение с таким client_id».
//
// Причина снаружи кода: пока OAuth-приложение Яндекса не опубликовано, оно
// пускает только аккаунт, под которым создано. Проверяем, что теперь окно
// «Моя музыка» говорит об этом прямо и показывает выход БЕЗ своего Диска
// (музыка с открытых чужих Дисков играет — pkg3-121), а технические шаги
// видит только владелец сервера.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { BUILD } from './build.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const read = p => readFileSync(join(ROOT, p), 'utf8');
const app = read('public/app.js');
const api = read('lib/api.js');
const sw = read('public/sw.js');
const pkg = read('package.json');

let good = 0, bad = 0;
const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ ПРОВАЛ: ') + m); if (c) good++; else bad++; };

console.log('\n══════════════════════════════════════════════════');
console.log('  pkg3-122: «400 · Неизвестно приложение» — понятно');
console.log('            и с выходом, который не требует Диска');
console.log('══════════════════════════════════════════════════\n');

const off = app.slice(app.indexOf('function ydRenderOff()'), app.indexOf('/** Загрузка списка аудиофайлов со всего Диска'));

console.log('  1. Окно прямо называет ошибку и её причину');
ok(off.includes('Неизвестно приложение с таким client_id'), 'в окне названа та самая ошибка Яндекса — человек узнаёт её');
ok(/дело не в вашем аккаунте и не в пароле/.test(off), 'сразу снято подозрение с аккаунта и пароля');
ok(/приложение[^]{0,120}ещё не опубликовано/.test(off.replace(/\s+/g, ' ')), 'названа настоящая причина: приложение не опубликовано');
ok(/пускает только аккаунт, под которым создано/.test(off.replace(/\s+/g, ' ')), 'и её следствие: пускает только свой аккаунт');

console.log('\n  2. Другу есть что делать без своего Диска');
ok(/Свой Диск при этом не обязателен/.test(off), 'другу сказано, что свой Диск не обязателен');
ok(/«Музыку участника»/.test(off) && /трека с Диска/.test(off), 'указан путь: «Музыка участника» → ▶ у трека с Диска');
ok(app.includes('data-musof-disk') && app.includes('data-musof-add'), 'и это правда работает: чужой дисковый трек играет и забирается «＋» (pkg3-121)');
ok(/api\/yadisk\/shared-href\?of=/.test(app), 'клиент по-прежнему просит ссылку на чужой Диск отдельным маршрутом');

console.log('\n  3. Технические шаги — только владельцу сервера');
ok(/const amAdmin = !!\(S\.me && S\.me\.isAdmin\);/.test(off), 'окно знает, владелец вы или участник');
ok(/oauth\.yandex\.ru → ваше приложение/.test(off), 'владельцу — что именно поправить в oauth.yandex.ru');
ok(/тестировщики|модераци/.test(off), 'и про модерацию/публикацию приложения');
ok(/\(amAdmin \? '<button class="mini" id="mus-disk-diag"/.test(off), 'кнопка «Проверить приложение» показывается только владельцу');

console.log('\n  4. Проверка приложения больше не обещает лишнего');
ok(/Если у другого аккаунта страница Яндекса всё равно пишет/.test(app), 'успешная проверка честно говорит про границу: сервер видит, а Яндекс решает по аккаунту');
ok(/значит приложение ещё не опубликовано/.test(app), 'и что это значит на практике');
ok(/у друзей и появляется эта страница Яндекса/.test(app), 'окно-подсказка объясняет, почему так у друзей');
ok(/Пока публикации нет, друзьям подключать свой Диск не нужно/.test(app), 'и повторяет выход без своего Диска');
ok(read('lib/yadisk.js').includes('async function probeAuth('), 'серверная проверка приложения (probeAuth) на месте — pkg3-121');

console.log('\n  5. Отметки выпуска');
const b2 = (/const BUILD = '([^']+)'/.exec(app) || [])[1];
const cache = (/const STATIC_CACHE = '([^']+)'/.exec(sw) || [])[1];
ok(b2 === BUILD, `отметка выпуска в клиенте и в тестах одна (${BUILD})`);
ok(((/const BUILD = '([^']+)'/.exec(api) || [])[1]) === BUILD, 'BUILD в lib/api.js тот же');
ok(new RegExp('\\| ' + BUILD + ' \\|').test(read('README.md')), `в журнале README есть строка ${BUILD}`);
ok(cache === 'sega-static-v136', `кэш оформления поднят (${cache}) — устройства получат правки`);
ok(pkg.includes('node test/ui122.mjs'), 'тест ui122 включён в цепочку npm test');

console.log(`\n  ИТОГ: ${good} ✓, ${bad ? bad + ' провалов' : 'провалов нет'}\n`);
process.exit(bad ? 1 : 0);
