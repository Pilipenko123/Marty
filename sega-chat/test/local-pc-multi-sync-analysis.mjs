import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {analyzeMultiSync,MAX_MEMBERS}=createRequire(import.meta.url)('../local-pc/multi-sync-analysis');
const hash=n=>n.toString(16).padStart(64,'0');
const file=(path,n)=>({path,type:'file',hash:hash(n),size:n});
const dir=path=>({path,type:'dir'});
const peer=(id,kind,snapshot)=>({id,kind,online:true,complete:true,snapshot});
const base=[dir('docs'),file('docs/note.txt',1),file('plain.txt',1)];
const peers=[peer('one','pc',base),peer('two','pc',base),peer('three','pc',base),peer('four','pc',base),peer('cloud','google',base)];
const run=(members=peers,extra={})=>analyzeMultiSync({enabled:true,baseConfirmed:true,base,members,...extra});
assert.deepEqual(run(),[]);
const changed=(m,path,n)=>m.map(x=>x.path===path?file(path,n):x);
const modified=peers.map(p=>({...p,snapshot:p.id==='three'?changed(base,'plain.txt',2):p.snapshot}));
assert.deepEqual(run(modified),[{path:'plain.txt',state:'changed',changedBy:['three']}]);
const identical=modified.map(p=>({...p,snapshot:p.id==='cloud'?changed(base,'plain.txt',2):p.snapshot}));
assert.deepEqual(run(identical),[{path:'plain.txt',state:'changed',changedBy:['three','cloud']}]);
const conflict=identical.map(p=>({...p,snapshot:p.id==='two'?changed(base,'plain.txt',3):p.snapshot}));
assert.deepEqual(run(conflict),[{path:'plain.txt',state:'conflict',changedBy:['two','three','cloud']}]);
// Облако и любой ПК равноправны в модели: удаление против правки — конфликт.
const deleted=peers.map(p=>({...p,snapshot:p.id==='cloud'?base.filter(x=>x.path!=='plain.txt'):p.snapshot}));
assert.deepEqual(run(deleted),[{path:'plain.txt',state:'changed',changedBy:['cloud']}]);
const deleteEdit=deleted.map(p=>({...p,snapshot:p.id==='four'?changed(base,'plain.txt',3):p.snapshot}));
assert.deepEqual(run(deleteEdit),[{path:'plain.txt',state:'conflict',changedBy:['four','cloud']}]);
const treeDelete=peers.map(p=>({...p,snapshot:p.id==='one'?base.filter(x=>!x.path.startsWith('docs')):p.snapshot}));
assert.deepEqual(run(treeDelete),[{path:'docs',state:'changed',changedBy:['one']}]);
const treeConflict=treeDelete.map(p=>({...p,snapshot:p.id==='cloud'?changed(base,'docs/note.txt',4):p.snapshot}));
assert.deepEqual(run(treeConflict),[{path:'docs',state:'conflict',changedBy:['one','cloud']}]);
const treeAdded=treeDelete.map(p=>({...p,snapshot:p.id==='two'?[...base,file('docs/new.txt',9)]:p.snapshot}));
assert.deepEqual(run(treeAdded),[{path:'docs',state:'conflict',changedBy:['one','two']}]);
const treeType=treeDelete.map(p=>({...p,snapshot:p.id==='two'?[file('docs',5),file('plain.txt',1)]:p.snapshot}));
assert.equal(run(treeType)[0].state,'conflict');
const googleAndYandex=[...peers,peer('cloud2','yandex',base)];assert.deepEqual(run(googleAndYandex),[]);
for(const patch of [{enabled:false},{baseConfirmed:false},{base:undefined}])assert.throws(()=>run(peers,patch));
assert.throws(()=>run([peers[0],{...peers[1],online:false}]));
assert.throws(()=>run([peers[0],{...peers[1],complete:false}]));
assert.throws(()=>run([peers[0],peers[0]]));
assert.throws(()=>run([peers[0],{...peers[1],id:'../x'}]));
assert.throws(()=>run([peers[0],{...peers[1],kind:'other'}]));
assert.throws(()=>run([peers[0]]));
assert.throws(()=>run(Array.from({length:MAX_MEMBERS+1},(_,i)=>peer('p'+i,'pc',[]))));
assert.throws(()=>run([peers[0],{...peers[1],snapshot:[file('docs/note.txt',1)]}]));
assert.throws(()=>run([peers[0],{...peers[1],snapshot:[file('PLAIN.txt',1)]}]));
assert.throws(()=>run([peers[0],{...peers[1],snapshot:[file('../bad',1)]}]));
assert.throws(()=>run([peers[0],{...peers[1],snapshot:[{path:'x',type:'file',hash:'unknown',size:1}]}]));
assert.throws(()=>run([peers[0],{...peers[1],snapshot:[file('a',1),file('A',1)]}]));
// Результат не является списком операций и не меняет переданные снимки.
assert(!run(deleteEdit).some(x=>'type' in x));assert.equal(base[1].hash,hash(1));
console.log('local-pc-multi-sync-analysis: 4 ПК и облака, конфликты, удаление и отказ при неполных данных проверены только в памяти; реальной синхронизации нет');
